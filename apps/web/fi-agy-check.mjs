import { chromium } from 'playwright'
import fs from 'node:fs'
const token = fs.readFileSync('/tmp/fi-server-token.txt','utf8').trim()
const page = await (await chromium.launch({ headless: true })).newPage()
await page.goto('http://127.0.0.1:3080/?token='+token, { timeout: 30000 })
await page.waitForTimeout(4500)
await page.getByRole('button', { name: 'Settings', exact: true }).click()
await page.waitForTimeout(1800)
await page.getByText('Models', { exact: true }).first().click().catch(() => null)
await page.waitForTimeout(3000)
const text = await page.locator('body').innerText().catch(() => 'none')
console.log('antigravity in text:', text.includes('Antigravity'))
console.log('sign in with antigravity:', text.includes('Sign in with Antigravity'))
console.log('gemini code assist:', text.includes('Gemini Code Assist'))
const strip = page.locator('section[aria-label*="Antigravity"]')
console.log('antigravity section count:', await strip.count())
const buttons = await strip.locator('button').allTextContents().catch(() => [])
console.log('antigravity buttons:', JSON.stringify(buttons))
process.exit(0)
